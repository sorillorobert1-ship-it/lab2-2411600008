<?php

namespace App\Services;

use App\Models\Product;
use App\Models\PurchaseOrder;
use App\Models\User;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\DB;

class ReorderService
{
    /** Number of past days used to compute average daily usage. */
    public const USAGE_PERIOD_DAYS = 30;

    /** Fixed cost of placing one order (S in the EOQ formula), in pesos. */
    public const ORDERING_COST = 500;

    /** Annual holding cost as a fraction of unit cost (H in the EOQ formula). */
    public const HOLDING_COST_RATE = 0.20;

    public function calculateAverageDailyUsage(Product $product, int $days = self::USAGE_PERIOD_DAYS): float
    {
        $used = $product->inventoryTransactions()
            ->where('type', 'out')
            ->where('created_at', '>=', now()->subDays($days))
            ->sum('quantity');

        return round($used / max($days, 1), 2);
    }

    /** Reorder Point = (Average Daily Usage x Lead Time) + Safety Stock */
    public function calculateReorderPoint(Product $product): int
    {
        $averageDailyUsage = $this->calculateAverageDailyUsage($product);

        $leadTime = $product->supplier->lead_time_days ?? 7;

        $safetyStock = $product->safety_stock ?? $product->reorder_level ?? 10;

        return (int) ceil(($averageDailyUsage * $leadTime) + $safetyStock);
    }

    /**
     * Simplified EOQ = sqrt((2 x D x S) / H), never below the stock deficit
     * or the supplier's minimum order quantity.
     */
    public function calculateOptimalOrderQuantity(Product $product): int
    {
        $annualDemand = $this->calculateAverageDailyUsage($product) * 365;
        $holdingCost = max((float) $product->unit_cost * self::HOLDING_COST_RATE, 0.01);
        $eoq = $annualDemand > 0 ? sqrt((2 * $annualDemand * self::ORDERING_COST) / $holdingCost) : 0;

        $deficit = $this->calculateReorderPoint($product) - $product->quantity_on_hand + $product->safety_stock;

        $minimumOrder = (int) ($product->suppliers->firstWhere('id', $product->supplier_id)?->pivot->minimum_order_quantity ?? 1);

        return (int) max(ceil($eoq), $deficit, $minimumOrder, 1);
    }

    /** Active products at or below their reorder point that are not already on an open purchase order. */
    public function getProductsNeedingReorder(): Collection
    {
        return Product::active()
            ->whereNotNull('supplier_id')
            ->whereHas('supplier', fn ($q) => $q->active())
            ->whereDoesntHave('purchaseOrderItems.purchaseOrder', fn ($q) => $q->active())
            ->with(['supplier', 'suppliers'])
            ->get()
            ->filter(fn (Product $product) => $product->quantity_on_hand <= $this->calculateReorderPoint($product))
            ->values();
    }

    public function groupProductsBySupplier($products): Collection
    {
        return collect($products)->groupBy('supplier_id');
    }

    /** Creates one draft purchase order per supplier for every product that needs reordering. */
    public function generatePurchaseOrders(?User $creator = null): Collection
    {
        $products = $this->getProductsNeedingReorder();

        $groupedBySupplier = $this->groupProductsBySupplier($products);

        $orders = collect();

        foreach ($groupedBySupplier as $supplierId => $products) {
            $orders->push(DB::transaction(function () use ($supplierId, $products, $creator) {
                $supplier = $products->first()->supplier;

                $order = PurchaseOrder::create([
                    'reference_number' => PurchaseOrder::generateReferenceNumber(),
                    'supplier_id' => $supplierId,
                    'created_by' => $creator?->id,
                    'status' => 'draft',
                    'order_date' => now(),
                    'expected_delivery_date' => now()->addDays($supplier->lead_time_days),
                    'terms' => $supplier->payment_terms,
                    'notes' => 'Automatically generated by the reorder point check.',
                    'is_auto_generated' => true,
                ]);

                foreach ($products as $product) {
                    $agreedCost = $product->suppliers->firstWhere('id', $supplierId)?->pivot->unit_cost;

                    $order->items()->create([
                        'product_id' => $product->id,
                        'quantity' => $this->calculateOptimalOrderQuantity($product),
                        'unit_price' => $agreedCost ?: $product->unit_cost,
                    ]);
                }

                return $order->calculateTotal()->load('supplier', 'items.product');
            }));
        }

        return $orders;
    }
}
